-- Product catalog schema. Portable between PostgreSQL (all deployments) and H2 in
-- PostgreSQL mode (zero-setup local run). Flyway migrations are immutable once merged:
-- never edit this file, add V2__..., V3__... instead.

CREATE TABLE product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(32)              NOT NULL,
    name        VARCHAR(120)             NOT NULL,
    description VARCHAR(1000),
    category    VARCHAR(60),
    price       NUMERIC(12, 2)           NOT NULL,
    stock       INTEGER                  NOT NULL,
    version     BIGINT                   NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_price CHECK (price >= 0),
    CONSTRAINT ck_product_stock CHECK (stock >= 0)
);

-- Filters and sorts used by GET /api/v1/products
CREATE INDEX idx_product_category ON product (category);
CREATE INDEX idx_product_price ON product (price);
CREATE INDEX idx_product_name ON product (name);
CREATE INDEX idx_product_created_at ON product (created_at);
